def seg_key(net, layer, x1, y1, x2, y2):
    return (net, layer, round(x1, 4), round(y1, 4), round(x2, 4), round(y2, 4))

delset = {seg_key(*d) for d in DEL_SEGS}
delvias = {(n, round(x, 4), round(y, 4)) for n, x, y in DEL_VIAS}

def parse_blocks(txt, tag):
    out = []
    i = 0
    while True:
        j = txt.find("(" + tag, i)
        if j < 0:
            break
        d = 0
        k = j
        while k < len(txt):
            if txt[k] == "(":
                d += 1
            elif txt[k] == ")":
                d -= 1
                if d == 0:
                    break
            k += 1
        out.append((j, k + 1))
        i = k + 1
    return out

spans = []
for (s, e) in parse_blocks(txt, "segment"):
    b = txt[s:e]
    nm = re.search(r'\(net "([^"]+)"\)', b)
    ly = re.search(r'\(layer "([^"]+)"\)', b)
    at = re.search(r'\(start ([-\d.]+) ([-\d.]+)\)\s*\(end ([-\d.]+) ([-\d.]+)\)', b)
    if not (nm and ly and at):
        continue
    n, l = nm.group(1), ly.group(1)
    x1, y1, x2, y2 = map(float, at.groups())
    k1 = seg_key(n, l, x1, y1, x2, y2)
    k2 = seg_key(n, l, x2, y2, x1, y1)
    if k1 in delset or k2 in delset:
        spans.append((s, e))

for (s, e) in parse_blocks(txt, "via"):
    b = txt[s:e]
    nm = re.search(r'\(net "([^"]+)"\)', b)
    at = re.search(r'\(at ([-\d.]+) ([-\d.]+)\)', b)
    if not (nm and at):
        continue
    if (nm.group(1), round(float(at.group(1)), 4), round(float(at.group(2)), 4)) in delvias:
        spans.append((s, e))

spans.sort(reverse=True)
for (s, e) in spans:
    # keep a clean file: also swallow the preceding newline+indent
    while s > 0 and txt[s - 1] in " \t":
        s -= 1
    if s > 0 and txt[s - 1] == "\n":
        s -= 1
    txt = txt[:s] + txt[e:]

add_lines = []
for (net, layer, x1, y1, x2, y2, w) in ADDS:
    add_lines.append(
        f'  (segment (start {x1} {y1}) (end {x2} {y2}) (width {w}) '
        f'(layer "{layer}") (net "{net}") (tstamp {abs(hash((net,layer,x1,y1,x2,y2)))%100000000:08x}-0000-4000-8000-000000000000))'
    )
# insert before the final zone / end of file: append before last ')'
idx = txt.rstrip().rfind(")")
txt = txt[:idx] + "\n" + "\n".join(add_lines) + "\n" + txt[idx:]

open(PCB, "w").write(txt)
print(f"removed {len(spans)} items; added {len(add_lines)} segments")
